export const dictionaries: Record<Locale, Dict> = { en, "zh-CN": zh };

/** Look a key up, with `{name}` interpolation. Falls back to English, then the key. */
export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const template = dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/** Pick a starting locale: stored choice, then the gateway setting, then the browser. */
export function detectLocale(gatewayLocale?: string): Locale {
  const stored = typeof localStorage !== "undefined" ? localStorage.getItem("local-router.locale") : null;
  if (stored === "en" || stored === "zh-CN") return stored;
  if (gatewayLocale === "en" || gatewayLocale === "zh-CN") return gatewayLocale;
  const nav = typeof navigator !== "undefined" ? navigator.language.toLowerCase() : "en";
  return nav.startsWith("zh") ? "zh-CN" : "en";
}
